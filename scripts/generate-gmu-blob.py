#!/usr/bin/env python3
"""Generate AdrenoGmuBlobV1.h -- the A630 GMU firmware as a C dword array -- or an
honest ABSENT stub when the bytes are not on this machine (ROUND 168).

WHY A GENERATOR AND NOT A COMMITTED HEADER
Same rule as scripts/generate-zap-blob.py (ROUND 109): a630_gmu.bin is somebody
else's signed firmware. scripts/data/adreno-a630-device-firmware.json records its
size and hash and promises the bytes never enter this repository, so the header
this script writes is a BUILD ARTIFACT: gitignored, regenerated on every build
host, never committed.

WHY DWORDS AND NOT BYTES
The consumer is not a filesystem or a PAS call: it is the CM3 ITCM bulk load.
Upstream a6xx_gmu_fw_load() (legacy path, a6xx_gmu.c) does

    gmu_write_bulk(gmu, REG_A6XX_GMU_CM3_ITCM_START, (u32 *)fw_image->data,
                   fw_image->size);

i.e. the image is a stream of little-endian 32-bit words written to consecutive
register word offsets starting at ITCM_START. Emitting bytes would force every
consumer to re-do the little-endian assembly; emitting dwords is the exact shape
the hardware sees. 32768 B / 4 = 8192 words (0x2000), which is also the size the
legacy gate checks ("0x8000 bytes = 0x2000 words", a6xx_gmu.c:741 / the model's
AdrenoGmuBootV1.c:96).

WHY ITCM AND DTCM ARE ONE CONTIGUOUS RUN
CM3_ITCM_START is word offset 0x0c00 and CM3_DTCM_START is 0x1c00 -- exactly
0x1000 words (16 KiB) apart. The legacy a630_gmu.bin is a single 32 KiB blob that
carries both halves back to back, which is why one bulk write covers both and why
the driver's DTCM signature read at `CM3_DTCM_START + 0xff8` lands on the last
word of this same image after the load.

THE ABSENT CASE, WHICH IS THE ONE THAT MATTERS
A generator that silently emitted zeros would hand the kernel an image that looks
valid -- right size, right shape -- and the ITCM load would "succeed" against
garbage. When the bytes are missing this script emits present=0, words=0 and a
single dummy dword, so a consumer that ignores the flag writes 4 bytes instead of
32 KiB, and every consumer must check the flag anyway.
"""
import argparse
import hashlib
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
# Same two candidates, same reasoning, as scripts/generate-zap-blob.py: the tree
# carries a `.cache/firmware` junction back to device/.cache/firmware, so the
# first entry resolves identically whether ROOT is device/ or the build tree.
# The caller passes --firmware-dir from board.toml anyway (kernel.py runs archive
# steps with cwd = tree, so a relative path there means <tree>/.cache/firmware).
FIRMWARE_CANDIDATES = (
    ROOT / '.cache' / 'firmware',
    ROOT.parent / 'tmp' / 'a630-device-fw',
)
OUT = ROOT / 'drivers' / 'NativeAdreno' / 'AdrenoGmuBlobV1.h'

# The pin. scripts/data/adreno-a630-device-firmware.json records this exact pair;
# a mismatch is a hard error because emitting it would launder a different blob in.
GMU_NAME = 'a630_gmu.bin'
GMU_BYTES = 32768
GMU_SHA256 = 'b07f90299ff2ae33948fcfd6ed67f53fbd287b5bf85ff2d43db11d4d32c1621f'
GMU_WORDS = GMU_BYTES // 4

# Word offsets, mirrored from drivers/NativeAdreno/AdrenoGmuBootV1.h so the header
# is self-describing (a consumer does not have to include the boot model to know
# where the image starts).
ITCM_WORD = 0x0c00
DTCM_WORD = 0x1c00


def dwords(data):
    """Little-endian dwords, six per row, 0x%08X so a diff is readable."""
    vals = struct.unpack('<%dI' % (len(data) // 4), data)
    rows = []
    for i in range(0, len(vals), 6):
        chunk = vals[i:i + 6]
        rows.append('    ' + ', '.join('0x%08XU' % v for v in chunk) + ',')
    return ('static const unsigned int adreno_gmu_image[%d] = {\n%s\n};'
            % (len(vals), '\n'.join(rows)))


def emit(present, data, out_path):
    sha = hashlib.sha256(data).hexdigest() if present else '0' * 64
    body = data if present else b'\x00\x00\x00\x00'
    text = '''// SPDX-License-Identifier: BSD-2-Clause-Patent
//
// AdrenoGmuBlobV1.h -- GENERATED by scripts/generate-gmu-blob.py. DO NOT EDIT.
// DO NOT COMMIT. This file carries proprietary firmware BYTES and is gitignored
// on purpose; the durable record is scripts/data/adreno-a630-device-firmware.json
// (size + hash, no bytes).
//
// ROUND 168. The A630 GMU firmware, as the 8192 little-endian dwords the legacy
// CM3 ITCM bulk load consumes: word offsets ITCM_WORD..ITCM_WORD+0x1FFF cover
// ITCM (16 KiB) and, contiguously, DTCM (16 KiB).
//
// PRESENT IS THE ONLY FLAG THAT MAY GATE USE. When it is 0 the array below is a
// single zero dword and the declared lengths are 0 -- a consumer that ignores the
// flag writes four bytes, not a plausible 32 KiB all-zero image.

#ifndef ADRENO_GMU_BLOB_V1_H
#define ADRENO_GMU_BLOB_V1_H

/* 1 only when this header was generated from the real device extraction. */
#define kAdrenoGmuBlobPresent %d

/* 32768 B / 4 = 8192 words; 0 when absent. */
#define kAdrenoGmuImageBytes %d
#define kAdrenoGmuImageWords %d

/* CM3 memory aperture word offsets in the GMU register window (0x0506A000). */
#define kAdrenoGmuItcmWord 0x%04Xu
#define kAdrenoGmuDtcmWord 0x%04Xu

/* Pinned provenance. All-zero when absent -- deliberately not a valid digest. */
static const char kAdrenoGmuImageSha256[] = "%s";

%s

#ifdef __cplusplus
extern "C" {
#endif
#ifdef __cplusplus
}
#endif
#endif /* ADRENO_GMU_BLOB_V1_H */
''' % (1 if present else 0,
       len(data) if present else 0,
       (len(data) // 4) if present else 0,
       ITCM_WORD, DTCM_WORD,
       sha,
       dwords(body))
    out_path.write_text(text, encoding='utf-8', newline='\n')


def self_check(present, out_path):
    """The generator's own gate: the header must SAY what it contains."""
    text = out_path.read_text(encoding='utf-8')
    checks = []

    def ck(cond, label):
        checks.append((bool(cond), label))

    ck(('kAdrenoGmuBlobPresent %d' % (1 if present else 0)) in text,
       'header declares present=%d' % (1 if present else 0))
    ck('GENERATED by scripts/generate-gmu-blob.py' in text, 'header says GENERATED')
    ck('DO NOT COMMIT' in text, 'header says DO NOT COMMIT')
    if present:
        ck('kAdrenoGmuImageBytes 32768' in text, 'length is 32768')
        ck('kAdrenoGmuImageWords 8192' in text, 'word count is 8192')
        ck(GMU_SHA256 in text, 'sha256 recorded')
        ck('adreno_gmu_image[8192]' in text, 'array declared at its real size')
        ck('kAdrenoGmuBlobPresent 0' not in text, 'present is not 0')
    else:
        ck('kAdrenoGmuImageBytes 0' in text, 'ABSENT: length is 0, not 32768')
        ck('kAdrenoGmuImageWords 0' in text, 'ABSENT: words is 0, not 8192')
        ck('"' + '0' * 64 + '"' in text, 'ABSENT: digest is all-zero')
        ck('kAdrenoGmuBlobPresent 1' not in text, 'ABSENT: present is not 1')
        ck('adreno_gmu_image[8192]' not in text,
           'ABSENT: no full-size all-zero array was emitted')
    return checks


def resolve_firmware_dir(explicit):
    if explicit:
        return pathlib.Path(explicit)
    for cand in FIRMWARE_CANDIDATES:
        if (cand / GMU_NAME).is_file():
            return cand
    return FIRMWARE_CANDIDATES[1]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--firmware-dir', default=None,
                    help='directory holding %s (default: .cache/firmware, then '
                         '<device>/tmp/a630-device-fw)' % GMU_NAME)
    ap.add_argument('--print-gitignore-rule', action='store_true',
                    help='print the .gitignore line this header needs and exit')
    args = ap.parse_args()

    if args.print_gitignore_rule:
        print('/drivers/NativeAdreno/AdrenoGmuBlobV1.h')
        return 0

    fw_dir = resolve_firmware_dir(args.firmware_dir)
    src = fw_dir / GMU_NAME
    present = src.is_file()
    data = b''
    if present:
        data = src.read_bytes()
        if len(data) != GMU_BYTES:
            print('error: %s is %d bytes, expected %d'
                  % (src, len(data), GMU_BYTES), file=sys.stderr)
            return 1
        sha = hashlib.sha256(data).hexdigest()
        if sha != GMU_SHA256:
            print('error: %s sha256 %s does not match the pinned %s'
                  % (src, sha, GMU_SHA256), file=sys.stderr)
            return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    emit(present, data, OUT)

    checks = self_check(present, OUT)
    bad = [label for ok, label in checks if not ok]
    for ok, label in checks:
        print('%s %s' % ('PASS' if ok else 'FAIL', label))
    print('wrote %s (%s, %d bytes)'
          % (OUT, 'present' if present else 'ABSENT', OUT.stat().st_size))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
