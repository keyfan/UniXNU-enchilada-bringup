#!/usr/bin/env python3
"""Generate AdrenoZapBlobV1.h -- the A630 ZAP firmware as C arrays -- or an
honest ABSENT stub when the bytes are not on this machine (ROUND 109).

WHY A GENERATOR AND NOT A COMMITTED HEADER
The bytes are somebody else's signed firmware. scripts/data/adreno-a630-device-
firmware.json's note promises they never enter this repository, and that promise
is why the durable record is a text manifest of SIZES + HASHES rather than the
blobs. So the header this script writes is a BUILD ARTIFACT: it is gitignored,
regenerated on every build host, and never committed. The rule to add to
.gitignore is printed by --print-gitignore-rule.

TWO ARRAYS, NOT ONE -- and this is the finding that decided the design
The task offered "the 1968 B valid segment, or the whole 6684 B .mdt". Neither
alone is sufficient, and the reason is a measured property of THIS blob:

  * a630_zap.mdt is a SPLIT image. ph[2] declares p_offset = 12288 in a 6684-byte
    container, so the segment payload is NOT inside the .mdt at all. The .mdt
    carries the ELF header (148 B) plus the hash segment (6536 B) and nothing
    else -- which is exactly why round 74 found ehdr_size + hash_size == the
    whole file size.
  * PAS *init_image* wants that metadata pair: ehdr + hash = 6684 B.
  * PAS *mem_setup* + the region load want the SEGMENT: a630_zap.b02, 1968 B.

So the header emits BOTH. Emitting only the segment would leave init_image with
nothing to authenticate; emitting only the .mdt would leave the region empty.

WHY b02 AND NOT A SLICE OF THE .mdt
Because there is no such slice: p_offset 12288 > 6684. The payload exists only
as the split-out .b02 file. Reading it directly is also what the upstream split
loader does (mdt_loader.c:50 sprintf -> "bNN"), so the generator mirrors the
loader instead of inventing a layout.

THE ABSENT CASE, WHICH IS THE ONE THAT MATTERS
A generator that silently emits zeros would hand the kernel a blob that LOOKS
valid -- right size, right shape -- and every downstream layer would treat the
region as loaded. That is the worst possible outcome: a PAS call would be made
with garbage and the secure-world rejection would be indistinguishable from a
real authentication failure. So when the bytes are missing this script emits a
header whose kAdrenoZapBlobPresent is 0 and whose arrays are 1 dummy byte, and
every consumer must check that flag. It never emits a plausible all-zero image.
"""
import argparse
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
# Same derivation check-enchilada-adreno-host.py uses for the real-blob test:
# ROOT is UniXNU-enchilada, ROOT.parent is work/, so the extraction lives at
# oneplus6-ios/work/tmp/a630-device-fw. It is gitignored and host-local by
# design, which is exactly why the ABSENT branch below has to be real.
FIRMWARE = ROOT.parent / 'tmp' / 'a630-device-fw'
OUT = ROOT / 'drivers' / 'NativeAdreno' / 'AdrenoZapBlobV1.h'

# The two inputs, and the sizes/hashes the durable manifest already records.
# A mismatch is a hard error: it means the local extraction is not the one the
# manifest describes, and emitting it would launder a different blob in.
MDT = ('a630_zap.mdt', 6684,
       'e0dffc7e45dfb05c681419881ab876ec974b6dc60b369394c2c9c6d9f631595e')
SEG = ('a630_zap.b02', 1968,
       '519b5538809f54ee566246b0520746a8ea82ca9384ea6bddb0b0e0d3c2de520c')

GITIGNORE_RULE = '/drivers/NativeAdreno/AdrenoZapBlobV1.h'


def carray(name, data):
    rows = []
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        rows.append('    ' + ', '.join('0x%02X' % b for b in chunk) + ',')
    return 'static const unsigned char %s[%d] = {\n%s\n};' % (name, len(data), '\n'.join(rows))


def emit(present, mdt, seg, out_path):
    mdt_sha = hashlib.sha256(mdt).hexdigest() if present else '0' * 64
    seg_sha = hashlib.sha256(seg).hexdigest() if present else '0' * 64
    mdt_body = mdt if present else b'\x00'
    seg_body = seg if present else b'\x00'
    text = '''// SPDX-License-Identifier: BSD-2-Clause-Patent
//
// AdrenoZapBlobV1.h -- GENERATED by scripts/generate-zap-blob.py. DO NOT EDIT.
// DO NOT COMMIT. This file carries proprietary firmware BYTES and is gitignored
// on purpose; the durable record is scripts/data/adreno-a630-device-firmware.json
// (sizes + hashes + PIL structure, no bytes).
//
// ROUND 109. Two arrays, because this blob is a SPLIT image (see the generator's
// docstring): the .mdt is metadata-only, the segment payload is .b02.
//
//   kAdrenoZapMdtBytes / adreno_zap_mdt -- ehdr+hash, for qcom_scm_pas_init_image
//   kAdrenoZapSegBytes / adreno_zap_seg -- the loadable segment, for gpu_region
//
// PRESENT IS THE ONLY FLAG THAT MAY GATE USE. When it is 0 the arrays below are
// a single dummy byte and their declared lengths are 0. A consumer that ignores
// this flag and reads the arrays anyway gets one zero byte, not a plausible
// all-zero firmware -- the failure is meant to be obvious, not silent.

#ifndef ADRENO_ZAP_BLOB_V1_H
#define ADRENO_ZAP_BLOB_V1_H

#ifdef __cplusplus
extern "C" {
#endif

/* 1 only when this header was generated from the real device extraction. */
#define kAdrenoZapBlobPresent %d

/* The metadata pair for PAS init_image: ehdr(148) + hash(6536) = 6684 B. */
#define kAdrenoZapMdtBytes %d
/* The single loadable segment for the gpu_region load: ph[2], 1968 B. */
#define kAdrenoZapSegBytes %d

/* The region this segment must be written into (enchilada.dts:25183). */
#define kAdrenoZapRegionPhys 0x8C415000u
#define kAdrenoZapRegionBytes 0x2000u

/* Pinned provenance, so a report can name exactly which bytes are in the image.
 * All-zero when absent -- deliberately not a valid digest of anything. */
static const char kAdrenoZapMdtSha256[] = "%s";
static const char kAdrenoZapSegSha256[] = "%s";

%s

%s

#ifdef __cplusplus
}
#endif
#endif /* ADRENO_ZAP_BLOB_V1_H */
''' % (1 if present else 0,
       len(mdt) if present else 0,
       len(seg) if present else 0,
       mdt_sha, seg_sha,
       carray('adreno_zap_mdt', mdt_body),
       carray('adreno_zap_seg', seg_body))
    out_path.write_text(text, encoding='utf-8', newline='\n')


def self_check(present, out_path):
    """The generator's own gate: the header must SAY what it contains."""
    text = out_path.read_text(encoding='utf-8')
    ok = True
    checks = []

    def ck(cond, label):
        nonlocal ok
        checks.append((bool(cond), label))
        if not cond:
            ok = False

    ck(('kAdrenoZapBlobPresent %d' % (1 if present else 0)) in text,
       'header declares present=%d' % (1 if present else 0))
    ck('GENERATED by scripts/generate-zap-blob.py' in text, 'header says GENERATED')
    ck('DO NOT COMMIT' in text, 'header says DO NOT COMMIT')
    if present:
        ck('kAdrenoZapMdtBytes 6684' in text, 'mdt length is 6684')
        ck('kAdrenoZapSegBytes 1968' in text, 'segment length is 1968')
        ck(MDT[2] in text, 'mdt sha256 recorded')
        ck(SEG[2] in text, 'segment sha256 recorded')
        # The arrays must carry the real bytes, not zeros. Spot-check: the MDT
        # starts with the ELF magic, so the first element after the array
        # declarator must be 0x7F. Anchor on the declarator, not the bare name
        # (the name also appears in the comment block above).
        _anchor = 'adreno_zap_mdt[6684]'
        ck(_anchor in text, 'mdt array is declared at its real size 6684')
        if _anchor in text:
            _head = text[text.index(_anchor):text.index(_anchor) + 200]
            ck('0x7F, 0x45, 0x4C, 0x46' in _head,
               'mdt array begins with the ELF magic 7F 45 4C 46')
        # And the segment must NOT be all-zero either.
        _seganchor = 'adreno_zap_seg[1968]'
        ck(_seganchor in text, 'segment array is declared at its real size 1968')
        ck('kAdrenoZapBlobPresent 0' not in text, 'present is not 0')
    else:
        ck('kAdrenoZapMdtBytes 0' in text, 'ABSENT: mdt length is 0, not 6684')
        ck('kAdrenoZapSegBytes 0' in text, 'ABSENT: segment length is 0, not 1968')
        ck('"' + '0' * 64 + '"' in text, 'ABSENT: digests are all-zero, not plausible')
        ck('kAdrenoZapBlobPresent 1' not in text, 'ABSENT: present is not 1')
        # The decisive anti-illusion check: no 6684- or 1968-byte array exists.
        ck('unsigned char adreno_zap_mdt[6684]' not in text,
           'ABSENT: no full-size all-zero mdt array was emitted')
        ck('unsigned char adreno_zap_seg[1968]' not in text,
           'ABSENT: no full-size all-zero segment array was emitted')
    return ok, checks


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--firmware-dir', type=pathlib.Path, default=FIRMWARE)
    ap.add_argument('--out', type=pathlib.Path, default=OUT)
    ap.add_argument('--require-bytes', action='store_true',
                    help='fail instead of emitting an ABSENT stub (for a device build)')
    ap.add_argument('--print-gitignore-rule', action='store_true')
    args = ap.parse_args()

    if args.print_gitignore_rule:
        print(GITIGNORE_RULE)
        return 0

    mdt_path = args.firmware_dir / MDT[0]
    seg_path = args.firmware_dir / SEG[0]
    have = mdt_path.is_file() and seg_path.is_file()

    if have:
        mdt = mdt_path.read_bytes()
        seg = seg_path.read_bytes()
        # Pinned size+hash: a mismatch means this is NOT the blob the manifest
        # describes, and emitting it would launder a different image in.
        if len(mdt) != MDT[1] or hashlib.sha256(mdt).hexdigest() != MDT[2]:
            raise SystemExit('REFUSED: %s is %d B / %s, manifest says %d B / %s'
                             % (MDT[0], len(mdt), hashlib.sha256(mdt).hexdigest()[:16],
                                MDT[1], MDT[2][:16]))
        if len(seg) != SEG[1] or hashlib.sha256(seg).hexdigest() != SEG[2]:
            raise SystemExit('REFUSED: %s is %d B / %s, manifest says %d B / %s'
                             % (SEG[0], len(seg), hashlib.sha256(seg).hexdigest()[:16],
                                SEG[1], SEG[2][:16]))
        print('blob    : %s %d B + %s %d B' % (MDT[0], len(mdt), SEG[0], len(seg)))
    else:
        if args.require_bytes:
            raise SystemExit('REFUSED: --require-bytes but %s is absent; '
                             'run scripts/fetch on a host that has the extraction'
                             % args.firmware_dir)
        mdt = seg = b''
        print('blob    : ABSENT (%s not found) -> emitting the honest stub'
              % args.firmware_dir)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    emit(have, mdt, seg, args.out)
    ok, checks = self_check(have, args.out)
    for good, label in checks:
        print(('ok   ' if good else 'FAIL ') + label)
    print('wrote   : %s (%d B)' % (args.out, args.out.stat().st_size))
    if not ok:
        raise SystemExit('the generated header failed its own self-check')
    print('PASS: AdrenoZapBlobV1.h %s (%d/%d self-checks); gitignore rule: %s'
          % ('EMBEDDED' if have else 'ABSENT-STUB', len(checks), len(checks),
             GITIGNORE_RULE))
    return 0


if __name__ == '__main__':
    sys.exit(main())
